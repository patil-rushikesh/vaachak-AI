-- Postgres baseline equivalent to SQLite migrations 1–7. Applied transactionally.
CREATE TABLE users(
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, role TEXT NOT NULL CHECK(role IN('teacher','student','learner')),
  name TEXT NOT NULL, email TEXT NOT NULL UNIQUE, pw_hash TEXT NOT NULL, created_at TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')), timezone TEXT NOT NULL DEFAULT 'UTC', language TEXT NOT NULL DEFAULT 'en', research_consent INTEGER NOT NULL DEFAULT 0);

CREATE TABLE sessions(
  token_hash TEXT PRIMARY KEY, user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  expires_at TEXT NOT NULL);

CREATE TABLE classes(
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, teacher_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  name TEXT NOT NULL, standard TEXT, section TEXT, pincode TEXT, state TEXT, district TEXT,
  language TEXT NOT NULL DEFAULT 'en', academic_year TEXT, code TEXT NOT NULL UNIQUE,
  color INTEGER NOT NULL DEFAULT 0, created_at TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')), archived INTEGER NOT NULL DEFAULT 0);

CREATE TABLE enrollments(
  class_id INTEGER NOT NULL REFERENCES classes(id) ON DELETE CASCADE,
  student_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  joined_at TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')), PRIMARY KEY(class_id,student_id));

CREATE TABLE recordings(
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, teacher_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  title TEXT NOT NULL, filename TEXT NOT NULL, mime TEXT NOT NULL, duration_ms INTEGER NOT NULL,
  created_at TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')));

CREATE TABLE assignments(
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, class_id INTEGER NOT NULL REFERENCES classes(id) ON DELETE CASCADE,
  teacher_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  student_id INTEGER REFERENCES users(id) ON DELETE CASCADE,
  recording_id INTEGER REFERENCES recordings(id) ON DELETE SET NULL,
  title TEXT NOT NULL, instructions TEXT, due_at TEXT, items TEXT NOT NULL,
  created_at TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')), archived INTEGER NOT NULL DEFAULT 0, revision INTEGER NOT NULL DEFAULT 1);

CREATE TABLE courses(
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, teacher_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  title TEXT NOT NULL, summary TEXT, level TEXT NOT NULL DEFAULT 'A1', language TEXT NOT NULL DEFAULT 'en',
  visibility TEXT NOT NULL DEFAULT 'public' CHECK(visibility IN('public','classes')),
  sequential INTEGER NOT NULL DEFAULT 1, status TEXT NOT NULL DEFAULT 'draft' CHECK(status IN('draft','published')),
  created_at TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')), updated_at TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')), archived INTEGER NOT NULL DEFAULT 0);

CREATE TABLE units(
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, course_id INTEGER NOT NULL REFERENCES courses(id) ON DELETE CASCADE,
  position INTEGER NOT NULL, title TEXT NOT NULL);

CREATE TABLE lessons(
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, unit_id INTEGER NOT NULL REFERENCES units(id) ON DELETE CASCADE,
  course_id INTEGER NOT NULL REFERENCES courses(id) ON DELETE CASCADE,
  position INTEGER NOT NULL, title TEXT NOT NULL, intro TEXT,
  recording_id INTEGER REFERENCES recordings(id) ON DELETE SET NULL, items TEXT NOT NULL DEFAULT '[]', archived INTEGER NOT NULL DEFAULT 0, revision INTEGER NOT NULL DEFAULT 1);

CREATE TABLE course_enrollments(
  course_id INTEGER NOT NULL REFERENCES courses(id) ON DELETE CASCADE,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  created_at TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')), PRIMARY KEY(course_id,user_id));

CREATE TABLE class_courses(
  class_id INTEGER NOT NULL REFERENCES classes(id) ON DELETE CASCADE,
  course_id INTEGER NOT NULL REFERENCES courses(id) ON DELETE CASCADE,
  assigned_at TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')), PRIMARY KEY(class_id,course_id));

CREATE TABLE insight_dismissals(
  class_id INTEGER NOT NULL REFERENCES classes(id) ON DELETE CASCADE,
  student_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  reason TEXT NOT NULL, teacher_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  created_at TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')), PRIMARY KEY(class_id,student_id,reason));

CREATE TABLE schema_migrations(version INTEGER PRIMARY KEY, applied_at TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')));

CREATE TABLE insight_actions(id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, class_id INTEGER NOT NULL REFERENCES classes(id) ON DELETE CASCADE,
            student_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE, reason TEXT NOT NULL,
            status TEXT NOT NULL, snooze_until TEXT, evidence_id INTEGER NOT NULL DEFAULT 0,
            assignment_id INTEGER REFERENCES assignments(id) ON DELETE SET NULL, updated_at TEXT NOT NULL,
            UNIQUE(class_id,student_id,reason));

CREATE TABLE reset_tokens(token_hash TEXT PRIMARY KEY, user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
            expires_at TEXT NOT NULL);

CREATE TABLE rate_limits(bucket TEXT NOT NULL, "window" INTEGER NOT NULL, count INTEGER NOT NULL,
            PRIMARY KEY(bucket,"window"));

CREATE TABLE privacy_events(id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id INTEGER REFERENCES users(id) ON DELETE CASCADE,
            action TEXT NOT NULL, created_at TEXT NOT NULL);

CREATE TABLE learning_profiles(user_id INTEGER PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE, goal TEXT NOT NULL DEFAULT 'everyday', difficulty TEXT NOT NULL DEFAULT 'starter', weekly_goal INTEGER NOT NULL DEFAULT 3, analytics INTEGER NOT NULL DEFAULT 0, updated_at TEXT NOT NULL);

CREATE TABLE practice_sessions(id TEXT PRIMARY KEY, user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE, request_hash TEXT NOT NULL, title TEXT NOT NULL, items TEXT NOT NULL, reason TEXT NOT NULL, position INTEGER NOT NULL DEFAULT 0, revision INTEGER NOT NULL DEFAULT 1, completed INTEGER NOT NULL DEFAULT 0, created_at TEXT NOT NULL, draft TEXT NOT NULL DEFAULT '{}');

CREATE TABLE attempts(
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  assignment_id INTEGER REFERENCES assignments(id) ON DELETE CASCADE, set_id TEXT,
  lesson_id INTEGER REFERENCES lessons(id) ON DELETE CASCADE,
  item_index INTEGER NOT NULL, kind TEXT NOT NULL, target TEXT, transcript TEXT NOT NULL,
  score INTEGER NOT NULL, accuracy INTEGER, result TEXT NOT NULL, audio_file TEXT, audio_mime TEXT,
  created_at TEXT NOT NULL DEFAULT (to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')), content_version INTEGER NOT NULL DEFAULT 0, item_snapshot TEXT NOT NULL DEFAULT '{}', input_mode TEXT NOT NULL DEFAULT 'legacy_unknown', transcript_origin TEXT NOT NULL DEFAULT 'legacy_unknown', rubric_version TEXT NOT NULL DEFAULT 'legacy_unknown', retry_of_attempt_id INTEGER REFERENCES attempts(id) ON DELETE SET NULL, disputed INTEGER NOT NULL DEFAULT 0, skill_ids TEXT NOT NULL DEFAULT '[]', practice_session_id TEXT REFERENCES practice_sessions(id) ON DELETE SET NULL);

CREATE TABLE submissions(user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
            client_uuid TEXT NOT NULL, request_hash TEXT NOT NULL, status TEXT NOT NULL,
            attempt_id INTEGER REFERENCES attempts(id) ON DELETE SET NULL, error_code TEXT,
            created_at TEXT NOT NULL, updated_at TEXT NOT NULL, PRIMARY KEY(user_id,client_uuid));

CREATE TABLE teacher_drafts(id TEXT PRIMARY KEY, user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE, payload TEXT NOT NULL, revision INTEGER NOT NULL DEFAULT 1, updated_at TEXT NOT NULL);

CREATE TABLE feedback_reports(id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE, category TEXT NOT NULL, message TEXT NOT NULL, attempt_id INTEGER REFERENCES attempts(id) ON DELETE SET NULL, helpful INTEGER, created_at TEXT NOT NULL);

CREATE TABLE product_events(id TEXT PRIMARY KEY, user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE, name TEXT NOT NULL, created_at TEXT NOT NULL);

CREATE TABLE conversations(id TEXT PRIMARY KEY, user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE, scenario TEXT NOT NULL, turns TEXT NOT NULL DEFAULT '[]', revision INTEGER NOT NULL DEFAULT 1, created_at TEXT NOT NULL);

CREATE TABLE transcriptions(id TEXT PRIMARY KEY, user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE, audio_file TEXT, mime TEXT, transcript TEXT, status TEXT NOT NULL, expires_at TEXT NOT NULL);

CREATE TABLE generation_jobs(id TEXT PRIMARY KEY, user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE, request_hash TEXT NOT NULL, payload TEXT NOT NULL, status TEXT NOT NULL, items TEXT NOT NULL DEFAULT '[]', lease_until TEXT, tries INTEGER NOT NULL DEFAULT 0, error_code TEXT, created_at TEXT NOT NULL, model TEXT);

CREATE TABLE knowledge_units(id TEXT PRIMARY KEY, skill_code TEXT NOT NULL, level TEXT NOT NULL DEFAULT 'A1', language TEXT NOT NULL DEFAULT 'en', title TEXT NOT NULL, body TEXT NOT NULL, example TEXT, source TEXT NOT NULL DEFAULT 'Vaachak reviewed', owner_id INTEGER REFERENCES users(id) ON DELETE CASCADE, visibility TEXT NOT NULL DEFAULT 'public', status TEXT NOT NULL DEFAULT 'approved', version INTEGER NOT NULL DEFAULT 1, created_at TEXT NOT NULL, reviewed_by INTEGER REFERENCES users(id) ON DELETE SET NULL, reviewed_at TEXT, published_at TEXT);

CREATE INDEX ix_attempts_user ON attempts(user_id, created_at);
CREATE INDEX ix_attempts_assignment ON attempts(assignment_id, user_id);
CREATE INDEX ix_assignments_class ON assignments(class_id, created_at);
CREATE INDEX ix_units_course ON units(course_id, position);
CREATE INDEX ix_lessons_unit ON lessons(unit_id, position);
CREATE INDEX ix_attempts_lesson ON attempts(lesson_id, user_id);
CREATE INDEX ix_submissions_status ON submissions(status,updated_at);
CREATE INDEX ix_practice_owner ON practice_sessions(user_id,created_at);
CREATE INDEX ix_generation_pending ON generation_jobs(status,created_at);
CREATE INDEX ix_knowledge_skill ON knowledge_units(skill_code,status,visibility);

CREATE VIEW scored_attempts AS SELECT * FROM attempts WHERE COALESCE(result::jsonb->>'evaluation_status', 'scored')='scored';
